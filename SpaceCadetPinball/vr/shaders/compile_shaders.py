#!/usr/bin/env python3
"""Compile the VR scene shaders to SPIR-V and embed them in vr_shaders.h.

Requires glslangValidator (package: glslang-tools / glslang).
Run from anywhere:  python3 SpaceCadetPinball/vr/shaders/compile_shaders.py
The generated header is committed, so normal builds do not need glslang.
"""
import os
import struct
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(os.path.dirname(HERE), "vr_shaders.h")
SHADERS = [("scene.vert", "SceneVert"), ("scene.frag", "SceneFrag")]


def compile_one(src):
    with tempfile.TemporaryDirectory() as tmp:
        spv = os.path.join(tmp, "out.spv")
        subprocess.check_call(["glslangValidator", "-V", "--target-env", "vulkan1.0", "-Os",
                               "-o", spv, os.path.join(HERE, src)])
        with open(spv, "rb") as f:
            data = f.read()
    return struct.unpack("<%dI" % (len(data) // 4), data)


def main():
    lines = ["// Generated by compile_shaders.py - do not edit.", "#pragma once", "#include <cstdint>", "",
             "namespace vr_shaders", "{"]
    for src, name in SHADERS:
        words = compile_one(src)
        lines.append("\tstatic const uint32_t %s[%d] = {" % (name, len(words)))
        for i in range(0, len(words), 8):
            lines.append("\t\t" + ", ".join("0x%08x" % w for w in words[i:i + 8]) + ",")
        lines.append("\t};")
    lines.append("}")
    with open(OUT, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", OUT)


if __name__ == "__main__":
    sys.exit(main())
